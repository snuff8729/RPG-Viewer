import { describe, it, expect } from "vitest";
import { MemoryFolder } from "../fs/folder";
import { PLUGIN_NAME, install, parsePluginsJs } from "../live/installer";
import { adapterPluginFile, getAdapterInstallStatus, installAdapter, uninstallAdapter, withAdapterEntry } from "./install";

const ORIGINAL = `// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{"name":"A","status":true,"description":"x","parameters":{}},\n{"name":"RPGViewerBridge","status":true,"description":"","parameters":{}},\n{"name":"Z","status":true,"description":"","parameters":{}}\n];\n`;
const names = async (f: MemoryFolder, p = "js/plugins.js") => parsePluginsJs((await f.readText(p))!)!.map(e => e.name);
const SRC = "/* ext */\n";

describe("adapter install", () => {
  it("writes the script and registers it right after RPGViewerBridge, keeping a backup", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    expect(await installAdapter(f, "data", "cpm", "CPM", SRC)).toEqual({ ok: true });
    expect(await names(f)).toEqual(["A", PLUGIN_NAME, "RPGViewerBridge_cpm", "Z"]);
    expect(await f.readText("js/plugins/RPGViewerBridge_cpm.js")).toBe(SRC);
    expect(await f.readText("rpg-viewer/plugins.js.bak")).toBe(ORIGINAL);
    expect(await getAdapterInstallStatus(f, "data", "cpm", SRC)).toEqual({ state: "installed", outdated: false });
    expect(await getAdapterInstallStatus(f, "data", "cpm", SRC.replace(/\n/g, "\r\n"))).toEqual({ state: "installed", outdated: false });
    expect(await getAdapterInstallStatus(f, "data", "cpm", "other")).toEqual({ state: "installed", outdated: true });
    // a second adapter goes after the first; reinstall does not duplicate
    await installAdapter(f, "data", "two", "Two", SRC);
    await installAdapter(f, "data", "cpm", "CPM", SRC);
    expect(await names(f)).toEqual(["A", PLUGIN_NAME, "RPGViewerBridge_cpm", "RPGViewerBridge_two", "Z"]);
  });

  it("uninstalls the entry and the file, leaving the rest", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    await installAdapter(f, "data", "cpm", "CPM", SRC);
    expect(await uninstallAdapter(f, "data", "cpm")).toEqual({ ok: true });
    expect(await names(f)).toEqual(["A", PLUGIN_NAME, "Z"]);
    expect(await f.readText("js/plugins/RPGViewerBridge_cpm.js")).toBeNull();
    expect(await getAdapterInstallStatus(f, "data", "cpm", SRC)).toEqual({ state: "notInstalled" });
    expect(await uninstallAdapter(f, "data", "cpm")).toEqual({ ok: true }); // nothing to do
  });

  it("without the main plugin: appended, and the main plugin installed later goes before it", async () => {
    const plain = ORIGINAL.replace(`{"name":"RPGViewerBridge","status":true,"description":"","parameters":{}},\n`, "");
    const f = new MemoryFolder({ "www/js/plugins.js": plain });
    await installAdapter(f, "www/data", "cpm", "CPM", SRC);
    expect(adapterPluginFile("www/data", "cpm")).toBe("www/js/plugins/RPGViewerBridge_cpm.js");
    expect(await f.readText("www/js/plugins/RPGViewerBridge_cpm.js")).toBe(SRC);
    expect(await names(f, "www/js/plugins.js")).toEqual(["A", "Z", "RPGViewerBridge_cpm"]);
    await install(f, "www/data", 'VERSION: "1"');
    expect(await names(f, "www/js/plugins.js")).toEqual(["A", "Z", PLUGIN_NAME, "RPGViewerBridge_cpm"]);
  });

  it("unsupported plugins.js", async () => {
    const f = new MemoryFolder({ "js/plugins.js": "garbage" });
    expect(await installAdapter(f, "data", "cpm", "CPM", SRC)).toMatchObject({ ok: false });
    expect(await getAdapterInstallStatus(f, "data", "cpm", SRC)).toEqual({ state: "unsupported" });
    expect(await getAdapterInstallStatus(new MemoryFolder({}), "data", "cpm", SRC)).toEqual({ state: "unsupported" });
  });

  it("withAdapterEntry turns a disabled entry back on in place", () => {
    const entries = parsePluginsJs(ORIGINAL)!;
    entries.push({ name: "RPGViewerBridge_cpm", status: false, description: "d", parameters: {} });
    const out = withAdapterEntry(entries, "cpm", "CPM");
    expect(out.map(e => e.name)).toEqual(["A", PLUGIN_NAME, "Z", "RPGViewerBridge_cpm"]);
    expect(out[3]).toMatchObject({ status: true, description: "d" });
    expect(entries[3].status).toBe(false); // input untouched
  });
});
