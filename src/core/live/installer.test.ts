import { describe, it, expect } from "vitest";
import { MemoryFolder } from "../fs/folder";
import { PLUGIN_NAME, formatPluginsJs, getInstallStatus, install, livePaths, parsePluginsJs, pluginVersionOf, uninstall } from "./installer";

const ORIGINAL = `// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n{"name":"A","status":true,"description":"x","parameters":{"k":"v \\"q\\""}},\n{"name":"B","status":false,"description":"","parameters":{}}\n];\n`;
const UNSUPPORTED = { ok: false, message: "이 게임은 자동 설치를 지원하지 않아요" };

describe("installer", () => {
  it("paths", () => {
    expect(livePaths("www/data").pluginsJs).toBe("www/js/plugins.js");
    expect(livePaths("www/data")).toMatchObject({ base: "www", pluginFile: "www/js/plugins/RPGViewerBridge.js", logDir: "www/rpg-viewer", logFile: "www/rpg-viewer/log.jsonl", liveFile: "www/rpg-viewer/live.json", backupFile: "www/rpg-viewer/plugins.js.bak" });
    expect(livePaths("data").logFile).toBe("rpg-viewer/log.jsonl");
    expect(livePaths("data").base).toBe("");
    expect(livePaths("data").pluginsJs).toBe("js/plugins.js");
  });
  it("version", () => expect(pluginVersionOf('x = { VERSION: "1.2.3" }')).toBe("1.2.3"));
  it("round-trips plugins.js", () => expect(formatPluginsJs(parsePluginsJs(ORIGINAL)!)).toBe(ORIGINAL));
  it("parses CRLF / no comments / blank lines", () => {
    const t = '\r\n\r\nvar $plugins =\r\n[\r\n{"name":"A","status":true,"description":"","parameters":{}},\r\n\r\n{"name":"B","status":true,"description":"","parameters":{}}\r\n];\r\n';
    expect(parsePluginsJs(t)!.map(e => e.name)).toEqual(["A", "B"]);
    expect(parsePluginsJs("garbage")).toBeNull();
    expect(parsePluginsJs("var $plugins =\n[{bad];")).toBeNull();
  });
  it("installs, preserving other entries", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    expect(await install(f, "data", 'x = { VERSION: "1.0.0" }')).toEqual({ ok: true });
    const entries = parsePluginsJs((await f.readText("js/plugins.js"))!)!;
    expect(entries.map(e => e.name)).toEqual(["A", "B", PLUGIN_NAME]);
    expect(entries[2]).toEqual({ name: PLUGIN_NAME, status: true, description: "RPG Viewer 기록 플러그인", parameters: {} });
    expect(entries[0]).toEqual(parsePluginsJs(ORIGINAL)![0]);
    expect(await f.readText("rpg-viewer/plugins.js.bak")).toBe(ORIGINAL);
    expect(await getInstallStatus(f, "data", "1.0.0")).toEqual({ state: "installed", version: "1.0.0", outdated: false });
    expect(await getInstallStatus(f, "data", "1.1.0")).toMatchObject({ outdated: true });
  });
  it("reinstall does not duplicate or overwrite backup", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    await install(f, "data", 'VERSION: "1.0.0"');
    await install(f, "data", 'VERSION: "1.0.1"');
    const entries = parsePluginsJs((await f.readText("js/plugins.js"))!)!;
    expect(entries.filter(e => e.name === PLUGIN_NAME)).toHaveLength(1);
    expect(await f.readText("rpg-viewer/plugins.js.bak")).toBe(ORIGINAL);
    expect(await getInstallStatus(f, "data", "1.0.1")).toMatchObject({ version: "1.0.1", outdated: false });
  });
  it("reinstall re-enables a disabled entry", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    await install(f, "data", 'VERSION: "1"');
    const es = parsePluginsJs((await f.readText("js/plugins.js"))!)!;
    es[2].status = false;
    await f.writeText("js/plugins.js", formatPluginsJs(es));
    await install(f, "data", 'VERSION: "1"');
    expect(parsePluginsJs((await f.readText("js/plugins.js"))!)![2].status).toBe(true);
  });
  it("uninstall removes only our entry and the file", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    await install(f, "data", 'VERSION: "1.0.0"');
    expect(await uninstall(f, "data")).toEqual({ ok: true });
    expect(parsePluginsJs((await f.readText("js/plugins.js"))!)!.map(e => e.name)).toEqual(["A", "B"]);
    expect(await f.stat("js/plugins/RPGViewerBridge.js")).toBeNull();
    expect(await f.stat("rpg-viewer/plugins.js.bak")).not.toBeNull();
    expect(await getInstallStatus(f, "data", "1.0.0")).toEqual({ state: "notInstalled" });
  });
  it("unsupported when plugins.js missing or unparsable", async () => {
    for (const files of [{} as Record<string, string>, { "js/plugins.js": "nonsense" }]) {
      const f = new MemoryFolder(files);
      expect(await install(f, "data", "x")).toEqual(UNSUPPORTED);
      expect(await f.stat("js/plugins/RPGViewerBridge.js")).toBeNull();
      expect(await f.stat("rpg-viewer/plugins.js.bak")).toBeNull();
      expect(await getInstallStatus(f, "data", "1")).toMatchObject({ state: "unsupported", reason: UNSUPPORTED.message });
    }
  });
  it("write failure -> permission message", async () => {
    const f = new MemoryFolder({ "js/plugins.js": ORIGINAL });
    f.writeText = async () => false;
    expect(await install(f, "data", "x")).toEqual({ ok: false, message: "쓰기 권한이 필요해요" });
  });
});
