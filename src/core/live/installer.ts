import type { GameFolder, WritableGameFolder } from "../fs/folder";

export const PLUGIN_NAME = "RPGViewerBridge";
const UNSUPPORTED = "이 게임은 자동 설치를 지원하지 않아요";
const NO_WRITE = "쓰기 권한이 필요해요";

export interface PluginEntry { name: string; status: boolean; description: string; parameters: Record<string, string> }
export interface LivePaths { base: string; pluginsJs: string; pluginFile: string; logDir: string; logFile: string; liveFile: string; controlFile: string; backupFile: string;
  /** 게임 창 단축키의 백업·복원 요청(플러그인 1.21.0, core/live/keyRequest) */
  requestFile: string;
}

export function livePaths(dataRoot: string): LivePaths {
  const parts = dataRoot.split("/").filter((s) => s !== "" && s !== ".");
  const base = parts.slice(0, -1).join("/");
  const j = (p: string) => (base ? `${base}/${p}` : p);
  return {
    base,
    pluginsJs: j("js/plugins.js"),
    pluginFile: j(`js/plugins/${PLUGIN_NAME}.js`),
    logDir: j("rpg-viewer"),
    logFile: j("rpg-viewer/log.jsonl"),
    liveFile: j("rpg-viewer/live.json"),
    controlFile: j("rpg-viewer/control.json"),
    backupFile: j("rpg-viewer/plugins.js.bak"),
    requestFile: j("rpg-viewer/request.json"),
  };
}

export function pluginVersionOf(source: string): string | null {
  return /VERSION:\s*"([^"]+)"/.exec(source)?.[1] ?? null;
}

export function parsePluginsJs(text: string): PluginEntry[] | null {
  const m = /\$plugins\s*=\s*\[/.exec(text);
  if (!m) return null;
  const start = m.index + m[0].length - 1;
  const end = text.lastIndexOf("]");
  if (end < start) return null;
  try {
    const v = JSON.parse(text.slice(start, end + 1));
    return Array.isArray(v) ? (v as PluginEntry[]) : null;
  } catch {
    return null;
  }
}

export function formatPluginsJs(entries: PluginEntry[]): string {
  return (
    "// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n" +
    entries.map((e) => JSON.stringify(e)).join(",\n") +
    "\n];\n"
  );
}

export type InstallStatus =
  | { state: "unsupported"; reason: string }
  | { state: "notInstalled" }
  | { state: "installed"; version: string | null; outdated: boolean };

export async function getInstallStatus(folder: GameFolder, dataRoot: string, bundledVersion: string): Promise<InstallStatus> {
  const p = livePaths(dataRoot);
  const text = await folder.readText(p.pluginsJs);
  const entries = text === null ? null : parsePluginsJs(text);
  if (!entries) return { state: "unsupported", reason: UNSUPPORTED };
  if (!entries.some((e) => e.name === PLUGIN_NAME)) return { state: "notInstalled" };
  const src = await folder.readText(p.pluginFile);
  const version = src === null ? null : pluginVersionOf(src);
  return { state: "installed", version, outdated: version !== bundledVersion };
}

export type InstallResult = { ok: true } | { ok: false; message: string };

export async function install(folder: WritableGameFolder, dataRoot: string, pluginSource: string): Promise<InstallResult> {
  const p = livePaths(dataRoot);
  const original = await folder.readText(p.pluginsJs);
  const entries = original === null ? null : parsePluginsJs(original);
  if (original === null || !entries) return { ok: false, message: UNSUPPORTED };
  const fail = { ok: false, message: NO_WRITE } as const;
  if ((await folder.stat(p.backupFile)) === null && !(await folder.writeText(p.backupFile, original))) return fail;
  if (!(await folder.writeText(p.pluginFile, pluginSource))) return fail;
  const own = entries.find((e) => e.name === PLUGIN_NAME);
  if (own) own.status = true;
  else {
    // 게임 전용 확장(RPGViewerBridge_<id>)이 먼저 설치돼 있으면 그 앞에 넣는다(확장은 기록 플러그인 뒤에 읽혀야 한다)
    const entry: PluginEntry = { name: PLUGIN_NAME, status: true, description: "RPG Viewer 기록 플러그인", parameters: {} };
    const ext = entries.findIndex((e) => typeof e?.name === "string" && e.name.startsWith(`${PLUGIN_NAME}_`));
    if (ext >= 0) entries.splice(ext, 0, entry);
    else entries.push(entry);
  }
  if (!(await folder.writeText(p.pluginsJs, formatPluginsJs(entries)))) return fail;
  return { ok: true };
}

export async function uninstall(folder: WritableGameFolder, dataRoot: string): Promise<InstallResult> {
  const p = livePaths(dataRoot);
  const text = await folder.readText(p.pluginsJs);
  const entries = text === null ? null : parsePluginsJs(text);
  if (!entries) return { ok: false, message: UNSUPPORTED };
  const rest = entries.filter((e) => e.name !== PLUGIN_NAME);
  if (!(await folder.writeText(p.pluginsJs, formatPluginsJs(rest)))) return { ok: false, message: NO_WRITE };
  if ((await folder.stat(p.pluginFile)) !== null && !(await folder.remove(p.pluginFile))) return { ok: false, message: NO_WRITE };
  return { ok: true };
}
