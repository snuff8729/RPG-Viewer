import { describe, expect, it } from "vitest";
import {
  buildFreeTextIndex, countLines, createMaskContext, cyrb53, hasKeyword, keepWordsOf, keywordHits, maskFileName, maskFileText,
  maskFreeText, maskJsonLines, maskJsonText, maskJsSource, maskPluginsJs, maskString, mirrorKindOf, scanFiles,
  scanText, tokenOf, unmaskText,
} from "./index";
import { MASK_VOCABULARY } from "./keywords";

// 테스트에 낱말을 직접 쓰지 않는다 — 목록에서 고른다.
const KW = MASK_VOCABULARY.find((w) => /^[a-z]{4,}$/.test(w) && !MASK_VOCABULARY.some((o) => o !== w && w.includes(o)))!;
const KW_JA = MASK_VOCABULARY.find((w) => /\p{Script=Katakana}/u.test(w))!;
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);
const T = (s: string) => tokenOf(s);
const TOKEN = /^T_[0-9a-f]{14}$/;

describe("token", () => {
  it("is deterministic and content-derived", () => {
    expect(tokenOf("アリス")).toBe(tokenOf("アリス"));
    expect(tokenOf("アリス")).not.toBe(tokenOf("ボブ"));
    expect(tokenOf("アリス")).toMatch(TOKEN);
    expect(cyrb53("a")).toBeLessThan(2 ** 53);
  });
});

describe("keywords", () => {
  it("matches on word-ish boundaries, not inside innocent words", () => {
    expect(KW).toBeTruthy();
    expect(hasKeyword(KW)).toBe(true);
    expect(hasKeyword(KW.toUpperCase())).toBe(true);
    expect(hasKeyword(`${KW}_01`)).toBe(true);
    expect(hasKeyword(`img-${KW}-2`)).toBe(true);
    expect(hasKeyword(`3${KW}9`)).toBe(true);
    expect(hasKeyword(`is${cap(KW)}Active`)).toBe(true);
    expect(hasKeyword(`${KW}yze`)).toBe(false);
    expect(hasKeyword(`qz${KW}`)).toBe(false);
    expect(hasKeyword("analyze the parameters")).toBe(false);
    expect(hasKeyword(`アリス${KW_JA}`)).toBe(true);
  });

  it("reports positions only", () => {
    expect(keywordHits(`ab ${KW}`)).toEqual([[3, 3 + KW.length]]);
  });
});

describe("maskString", () => {
  it("keeps escape codes, newlines and ASCII; tokenizes non-ASCII runs", () => {
    expect(maskString("\\C[2]アリス\\C[0]: Hello\n\\N[1]の部屋")).toBe(`\\C[2]${T("アリス")}\\C[0]: Hello\n\\N[1]${T("の部屋")}`);
    expect(maskString("  こんにちは  ")).toBe(`  ${T("こんにちは")}  `);
    expect(maskString("\\{\\.\\|\\!\\>\\<\\^\\$")).toBe("\\{\\.\\|\\!\\>\\<\\^\\$");
    expect(maskString("$gameVariables.value(3) img/pictures/Title_01")).toBe("$gameVariables.value(3) img/pictures/Title_01");
  });

  it("keeps notetag structure and masks plugin-style escape arguments", () => {
    expect(maskString("<Price: 100>\n<名前:アリス>")).toBe(`<Price: 100>\n<${T("名前")}:${T("アリス")}>`);
    expect(maskString("\\n<アリス>やあ")).toBe(`\\n<${T("アリス")}>${T("やあ")}`);
  });

  it("never puts backslashes or quotes inside a token (safe to unmask inside JSON/JS strings)", () => {
    expect(maskString("\\\\ アリス\\ :\\ \"やあ\"")).toBe(`\\\\ ${T("アリス")}\\ :\\ "${T("やあ")}"`);
    expect(maskString("アリス\tやあ\rボブ　さん")).toBe(`${T("アリス")}\t${T("やあ")}\r${T("ボブ　さん")}`);
  });

  it("groups space-separated non-ASCII words (Korean sentences) into one token", () => {
    expect(maskString("앨리스의 방에 간다 Lv.5")).toBe(`${T("앨리스의 방에 간다")} Lv.5`);
  });

  it("masks ASCII words with keywords only", () => {
    expect(maskString(`Go to the ${KW} room`)).toBe(`Go to the ${T(KW)} room`);
    expect(maskString(`${cap(KW)}_Scene_01`)).toBe(T(`${cap(KW)}_Scene_01`));
  });

  it("records the dictionary and counts", () => {
    const ctx = createMaskContext();
    maskString("アリス", ctx); maskString("アリス", ctx);
    expect(ctx.dict.get(T("アリス"))).toBe("アリス");
    expect(ctx.replaced).toBe(2);
  });
});

describe("maskFileName", () => {
  it("masks folder and base names consistently with data references, keeps extension", () => {
    expect(maskFileName("img/pictures/アリス_01.png")).toBe(`img/pictures/${T("アリス_01")}.png`);
    expect(maskFileName("img/pictures/サブ/顔.rpgmvp")).toBe(`img/pictures/${T("サブ")}/${T("顔")}.rpgmvp`);
    // 데이터 쪽 그림 이름 "サブ/顔"와 같은 결과
    expect(maskString("サブ/顔")).toBe(`${T("サブ")}/${T("顔")}`);
    expect(maskFileName("audio/bgm/Battle1.ogg")).toBe("audio/bgm/Battle1.ogg");
  });
});

describe("JSON", () => {
  it("masks string values, keeps format, ASCII keys and numbers", () => {
    const src = '[\nnull,\n{"id":1,"name":"アリス","note":"<Price: 100>","list":[{"code":401,"parameters":["こんにちは"]}]}\n]';
    const out = maskJsonText(src);
    expect(out).toBe(`[\nnull,\n{"id":1,"name":"${T("アリス")}","note":"<Price: 100>","list":[{"code":401,"parameters":["${T("こんにちは")}"]}]}\n]`);
    expect(JSON.parse(out)[1].id).toBe(1);
  });

  it("recurses into nested JSON strings (MZ struct params)", () => {
    const inner = JSON.stringify({ Text: "アリス", Size: "24" });
    const out = maskJsonText(JSON.stringify({ Param: inner }));
    const parsed = JSON.parse(JSON.parse(out).Param);
    expect(parsed).toEqual({ Text: T("アリス"), Size: "24" });
  });

  it("plugins.js: plugin name equals masked plugin file base name", () => {
    const src = `// Generated by RPG Maker.\nvar $plugins =\n[\n{"name":"アリス_Core","status":true,"description":"説明","parameters":{"表示":"true"}}\n];\n`;
    const out = maskPluginsJs(src);
    expect(out.startsWith("// Generated by RPG Maker.\nvar $plugins =\n[\n")).toBe(true);
    const entry = JSON.parse(out.slice(out.indexOf("{"), out.lastIndexOf("}") + 1));
    expect(`js/plugins/${entry.name}.js`).toBe(maskFileName("js/plugins/アリス_Core.js"));
    expect(Object.keys(entry.parameters)).toEqual([T("表示")]);
  });

  it("log lines are masked one by one", () => {
    expect(maskJsonLines('{"v":1,"type":"text","text":"やあ"}\nbroken アリス\n')).toBe(`{"v":1,"type":"text","text":"${T("やあ")}"}\nbroken ${T("アリス")}\n`);
  });
});

describe("plugin JS", () => {
  const src = [
    "/*:",
    " * @plugindesc テスト用",
    " * @param 名前",
    " */",
    "(function() {",
    "  var p = PluginManager.parameters('テスト');",
    "  var s = \"\\\\C[2]アリス\";  // 名前",
    "  var t = `行1",
    "行2 ${p}`;",
    "  var r = /アリス/g;",
    `  function is${cap(KW)}Active() { return 'line1\\`,
    "line2'; }",
    "  var アリス = 1;",
    "})();",
  ].join("\n");

  it("masks comments, literals, regexes and sensitive identifiers; keeps lines", () => {
    const ctx = createMaskContext();
    const r = maskJsSource(src, ctx);
    expect(r.fallback).toBe(false);
    expect(countLines(r.text)).toBe(countLines(src));
    const lines = r.text.split("\n");
    expect(lines[1]).toBe(` * @plugindesc ${T("テスト用")}`);
    expect(lines[2]).toBe(` * @param ${T("名前")}`);
    expect(lines[5]).toBe(`  var p = PluginManager.parameters('${T("テスト")}');`);
    expect(lines[6]).toBe(`  var s = "\\\\C[2]${T("アリス")}";  // ${T("名前")}`);
    expect(lines[9]).toBe(`  var r = /${T("アリス")}/g;`);
    expect(lines[10]).toContain(`function ${T(`is${cap(KW)}Active`)}()`);
    expect(lines[12]).toBe(`  var ${T("アリス")} = 1;`);
    expect(r.text).not.toMatch(/[぀-ヿ一-鿿]/);
    expect(scanText(r.text)).toEqual([]);
    expect(r.text).toContain("PluginManager.parameters");
  });

  it("falls back to line masking on syntax errors, still keeping lines", () => {
    const bad = "var a = 'アリス\nvar b = 1;\n// コメント\n"; // 닫히지 않은 문자열(토크나이저 오류)
    const ctx = createMaskContext();
    const r = maskJsSource(bad, ctx);
    expect(r.fallback).toBe(true);
    expect(ctx.jsFallbacks).toBe(1);
    expect(countLines(r.text)).toBe(countLines(bad));
    expect(r.text).not.toMatch(/[぀-ヿ]/);
  });
});

describe("free text, unmask, scan", () => {
  it("replaces known game runs longest-first, keeps the user's own Korean words", () => {
    const ctx = createMaskContext();
    maskString("アリス", ctx); maskString("アリスの部屋", ctx); maskString("앨리스", ctx);
    const index = buildFreeTextIndex(ctx.dict);
    const out = maskFreeText(`문제: アリスの部屋 에서 앨리스가 멈춰요. ${KW} 장면. 未知の文字`, index);
    expect(out).toBe(`문제: ${T("アリスの部屋")} 에서 ${T("앨리스")}가 멈춰요. ${T(KW)} 장면. ${T("未知の文字")}`);
  });

  it("does not match inside words and leaves kept (viewer template) words alone", () => {
    const ctx = createMaskContext();
    maskString("들어", ctx); maskString("전투", ctx); maskString("앨리스", ctx);
    const index = buildFreeTextIndex(ctx.dict);
    const keep = keepWordsOf(`${T("앨리스")} 전투 화면을 만들어요`);
    expect(keep).toContain("전투");
    expect(keep).not.toContain(T("앨리스"));
    expect(maskFreeText("앨리스가 전투 화면을 만들어요", index, undefined, keep)).toBe(`${T("앨리스")}가 전투 화면을 만들어요`);
    expect(maskFreeText("전투", index)).toBe(T("전투"));
  });

  it("unmask round-trips and reports unknown tokens", () => {
    const ctx = createMaskContext();
    const masked = maskString("\\C[2]アリス\\C[0] says hi, 앨리스", ctx);
    const r = unmaskText(`${masked} T_00000000000000`, ctx.dict);
    expect(r.text).toBe("\\C[2]アリス\\C[0] says hi, 앨리스 T_00000000000000");
    expect(r.replaced).toBe(2);
    expect(r.unknown).toEqual(["T_00000000000000"]);
  });

  it("safety scan returns locations only", () => {
    const res = scanFiles([{ path: "a.txt", text: `ok\nfine ${KW}\n` }, { path: "b.txt", text: "clean" }]);
    expect(res).toEqual({ count: 1, hits: [{ file: "a.txt", line: 2 }] });
    expect(JSON.stringify(res)).not.toContain(KW);
  });

  it("no keyword is made only of hex letters (tokens never trip the scan)", () => {
    expect(MASK_VOCABULARY.filter((w) => /^[a-f]+$/i.test(w))).toEqual([]);
    expect(scanText(Array.from({ length: 50 }, (_, i) => T(`x${i}`)).join(" "))).toEqual([]);
  });
});

describe("mirror kinds", () => {
  it("classifies MV and MZ layouts", () => {
    expect(mirrorKindOf("www/data/Map001.json", "www")).toBe("json");
    expect(mirrorKindOf("data/Map001.json", "")).toBe("json");
    expect(mirrorKindOf("www/js/plugins.js", "www")).toBe("plugins");
    expect(mirrorKindOf("js/plugins/Foo.js", "")).toBe("pluginJs");
    expect(mirrorKindOf("rpg-viewer/log.jsonl", "")).toBe("jsonl");
    expect(mirrorKindOf("www/img/pictures/a.png", "www")).toBe("placeholder");
    expect(mirrorKindOf("www/rpg-viewer/pictures/sub/a.png", "www")).toBe("placeholder");
    expect(mirrorKindOf("rpg-viewer/control.json", "")).toBeNull();
    expect(mirrorKindOf("www/rpg-viewer/missing-pictures.json", "www")).toBe("json");
    expect(mirrorKindOf("package.json", "www")).toBe("json");
    expect(mirrorKindOf("www/index.html", "www")).toBe("text");
    expect(mirrorKindOf("www/save/file1.rpgsave", "www")).toBeNull();
    expect(mirrorKindOf("save/file1.rmmzsave", "")).toBeNull();
    expect(mirrorKindOf("js/rmmz_core.js", "")).toBeNull();
  });

  it("masks html titles", () => {
    expect(maskFileText("text", "<title>アリスの冒険</title>").text).toBe(`<title>${T("アリスの冒険")}</title>`);
  });
});
